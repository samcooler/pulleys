"""PlatformIO pre-build script: bake the default game into the firmware.

Turns game_state_machine/state_config.yaml into a generated header,
game_default.h, and puts its folder on the include path. Envs opt in with

    extra_scripts = pre:tools/embed_game.py

The header carries:
  GAME_DEFAULT_JSON       the whole config, for the arbiter to run at boot
  GAME_CUE_HASH           fingerprint of the cue table (see lib/pulleys_cues)
  GAME_CUE_GROUPS / _GROUP_START / _NAMES
                          the cue table flattened: group g's cues are
                          GAME_CUE_NAMES[GAME_CUE_GROUP_START[g] ..
                          GAME_CUE_GROUP_START[g + 1]). The bridge turns a
                          [folder, file] pair back into a name with this.

A bad config fails the build. The file is rewritten only when its content
changes, so a no-op edit to the YAML does not recompile everything.
"""

import json
import os
import sys

Import("env")  # noqa: F821 -- provided by SCons

try:
    import yaml  # noqa: F401
except ImportError:
    env.Execute("$PYTHONEXE -m pip install pyyaml")  # noqa: F821
    import yaml  # noqa: F401

project = env["PROJECT_DIR"]  # noqa: F821
sys.path.insert(0, os.path.join(project, "tools"))
import game_to_json  # noqa: E402

config_path = os.path.join(project, "game_state_machine", "state_config.yaml")
cfg = game_to_json.load_config(config_path)
errors = game_to_json.validate(cfg)
if errors:
    sys.stderr.write(f"{config_path}:\n")
    for e in errors:
        sys.stderr.write(f"  {e}\n")
    env.Exit(1)  # noqa: F821

body = json.dumps(cfg, separators=(",", ":"))
assert ")GAMEJSON\"" not in body

names, starts = [], []
for group, cues in cfg["cues"].items():
    starts.append(len(names))
    names.extend(cues or [])
starts.append(len(names))

header = f"""// Generated by tools/embed_game.py from state_config.yaml. Do not edit.
#pragma once
#include <stdint.h>

static const char GAME_DEFAULT_JSON[] = R"GAMEJSON({body})GAMEJSON";

static const uint16_t GAME_CUE_HASH = 0x{game_to_json.cue_hash(cfg):04X};
static const uint8_t  GAME_CUE_GROUPS = {len(starts) - 1};
static const uint16_t GAME_CUE_GROUP_START[] = {{{", ".join(map(str, starts))}}};
static const char* const GAME_CUE_NAMES[] = {{
{os.linesep.join(f'    "{n}",' for n in names)}
}};
"""

out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
os.makedirs(out_dir, exist_ok=True)
out = os.path.join(out_dir, "game_default.h")
if not os.path.exists(out) or open(out).read() != header:
    with open(out, "w") as f:
        f.write(header)
env.Append(CPPPATH=[out_dir])  # noqa: F821
